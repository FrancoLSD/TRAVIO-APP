/// null si la moneda no está en la lista (el proveedor no la cubre).
Currency? findCurrency(String code) =>
    currencies.where((c) => c.code == code).firstOrNull;

Currency currencyByCode(String code) => currencies.firstWhere(
  (c) => c.code == code,
  orElse: () => currencies.firstWhere((c) => c.code == 'USD'),
);

/// Moneda de la región del dispositivo (ej. 'es_ES' → EUR); USD si no se reconoce.
Currency suggestedCurrency(String locale) {
  try {
    return currencyByCode(
      NumberFormat.simpleCurrency(locale: locale).currencyName ?? 'USD',
    );
  } catch (_) {
    return currencyByCode('USD');
  }
}
